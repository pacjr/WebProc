-- usuarios_clientes: read own active membership
CREATE POLICY "membership_select_own"
  ON webproc.usuarios_clientes
  FOR SELECT
  TO authenticated
  USING (
    user_id = auth.uid()
    AND ativo = true
  );

-- clientes: read active client linked to membership
CREATE POLICY "clientes_select_member"
  ON webproc.clientes
  FOR SELECT
  TO authenticated
  USING (
    ativo = true
    AND EXISTS (
      SELECT 1
      FROM webproc.usuarios_clientes uc
      WHERE uc.cliente_id = clientes.id
        AND uc.user_id = auth.uid()
        AND uc.ativo = true
    )
  );

-- processos: same-client read
CREATE POLICY "processos_select_same_client"
  ON webproc.processos
  FOR SELECT
  TO authenticated
  USING (
    EXISTS (
      SELECT 1
      FROM webproc.usuarios_clientes uc
      INNER JOIN webproc.clientes c ON c.id = uc.cliente_id
      WHERE uc.user_id = auth.uid()
        AND uc.ativo = true
        AND c.ativo = true
        AND uc.cliente_id = processos.cliente_id
    )
  );

-- processos: insert for active client, creator = auth.uid()
CREATE POLICY "processos_insert_member"
  ON webproc.processos
  FOR INSERT
  TO authenticated
  WITH CHECK (
    created_by = auth.uid()
    AND EXISTS (
      SELECT 1
      FROM webproc.usuarios_clientes uc
      INNER JOIN webproc.clientes c ON c.id = uc.cliente_id
      WHERE uc.user_id = auth.uid()
        AND uc.ativo = true
        AND c.ativo = true
        AND uc.cliente_id = processos.cliente_id
    )
  );

-- processos: update only own created records within active client
CREATE POLICY "processos_update_creator"
  ON webproc.processos
  FOR UPDATE
  TO authenticated
  USING (
    created_by = auth.uid()
    AND EXISTS (
      SELECT 1
      FROM webproc.usuarios_clientes uc
      INNER JOIN webproc.clientes c ON c.id = uc.cliente_id
      WHERE uc.user_id = auth.uid()
        AND uc.ativo = true
        AND c.ativo = true
        AND uc.cliente_id = processos.cliente_id
    )
  )
  WITH CHECK (
    created_by = auth.uid()
    AND EXISTS (
      SELECT 1
      FROM webproc.usuarios_clientes uc
      INNER JOIN webproc.clientes c ON c.id = uc.cliente_id
      WHERE uc.user_id = auth.uid()
        AND uc.ativo = true
        AND c.ativo = true
        AND uc.cliente_id = processos.cliente_id
    )
  );

-- processo_documentos: same-client read via process
CREATE POLICY "processo_documentos_select_same_client"
  ON webproc.processo_documentos
  FOR SELECT
  TO authenticated
  USING (
    EXISTS (
      SELECT 1
      FROM webproc.processos p
      INNER JOIN webproc.usuarios_clientes uc ON uc.cliente_id = p.cliente_id
      INNER JOIN webproc.clientes c ON c.id = uc.cliente_id
      WHERE p.id_proc = processo_documentos.id_proc
        AND uc.user_id = auth.uid()
        AND uc.ativo = true
        AND c.ativo = true
    )
  );
