-- WP-01: Greenfield WebProc schema (does not modify legacy public objects)

CREATE SCHEMA IF NOT EXISTS webproc;

GRANT USAGE ON SCHEMA webproc TO authenticated;

-- ---------------------------------------------------------------------------
-- updated_at trigger (webproc schema only)
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION webproc.set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

-- ---------------------------------------------------------------------------
-- A1. webproc.clientes
-- TD-WP-01: temporary client master until FlowProc integration
-- ---------------------------------------------------------------------------

CREATE TABLE webproc.clientes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo_cliente bigint NOT NULL,
  nome text NOT NULL,
  ativo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT clientes_codigo_cliente_unique UNIQUE (codigo_cliente)
);

CREATE TRIGGER clientes_set_updated_at
  BEFORE UPDATE ON webproc.clientes
  FOR EACH ROW
  EXECUTE FUNCTION webproc.set_updated_at();

-- ---------------------------------------------------------------------------
-- A2. webproc.usuarios_clientes
-- ---------------------------------------------------------------------------

CREATE TABLE webproc.usuarios_clientes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id bigint NOT NULL REFERENCES webproc.clientes (id),
  user_id uuid REFERENCES auth.users (id),
  email text NOT NULL,
  ativo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX usuarios_clientes_cliente_email_unique
  ON webproc.usuarios_clientes (cliente_id, lower(email));

CREATE UNIQUE INDEX usuarios_clientes_cliente_user_unique
  ON webproc.usuarios_clientes (cliente_id, user_id)
  WHERE user_id IS NOT NULL;

CREATE TRIGGER usuarios_clientes_set_updated_at
  BEFORE UPDATE ON webproc.usuarios_clientes
  FOR EACH ROW
  EXECUTE FUNCTION webproc.set_updated_at();

-- ---------------------------------------------------------------------------
-- A3. webproc.processos
-- ---------------------------------------------------------------------------

CREATE TABLE webproc.processos (
  id_proc bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id bigint NOT NULL REFERENCES webproc.clientes (id),
  created_by uuid NOT NULL REFERENCES auth.users (id),
  n_processo text,
  exec_prov text,
  nome_cli text,
  reclamante text,
  reclamado text,
  instituicao text,
  instrucao text,
  obs text,
  dt_entrada timestamptz NOT NULL DEFAULT now(),
  dt_fatal timestamptz,
  status text NOT NULL DEFAULT 'EM_PREENCHIMENTO',
  pendente_at timestamptz,
  importado_at timestamptz,
  concluido_at timestamptz,
  cancelado_at timestamptz,
  cancelado_por uuid REFERENCES auth.users (id),
  motivo_cancelamento text,
  origem_cancelamento text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT processos_status_check CHECK (
    status IN (
      'EM_PREENCHIMENTO',
      'PENDENTE',
      'IMPORTADO',
      'CONCLUIDO',
      'CANCELADO'
    )
  )
);

CREATE TRIGGER processos_set_updated_at
  BEFORE UPDATE ON webproc.processos
  FOR EACH ROW
  EXECUTE FUNCTION webproc.set_updated_at();

-- ---------------------------------------------------------------------------
-- A4. webproc.processo_documentos
-- ---------------------------------------------------------------------------

CREATE TABLE webproc.processo_documentos (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  id_proc bigint NOT NULL REFERENCES webproc.processos (id_proc) ON DELETE CASCADE,
  tipo text NOT NULL,
  nome text,
  url text,
  object_key text,
  nome_arquivo text,
  content_type text,
  tamanho bigint,
  created_by uuid NOT NULL REFERENCES auth.users (id),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT processo_documentos_tipo_check CHECK (tipo IN ('LINK', 'ARQUIVO')),
  CONSTRAINT processo_documentos_link_arquivo_check CHECK (
    (tipo = 'LINK' AND url IS NOT NULL AND object_key IS NULL)
    OR (tipo = 'ARQUIVO' AND object_key IS NOT NULL AND url IS NULL)
  )
);

-- ---------------------------------------------------------------------------
-- Grants for authenticated role
-- ---------------------------------------------------------------------------

GRANT SELECT, INSERT, UPDATE ON webproc.clientes TO authenticated;
GRANT SELECT ON webproc.usuarios_clientes TO authenticated;
GRANT SELECT, INSERT, UPDATE ON webproc.processos TO authenticated;
GRANT SELECT ON webproc.processo_documentos TO authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA webproc TO authenticated;

